// src/components/common/Magnetic.tsx
// ReactBits-inspired Magnetic wrapper component.
// Smoothly pulls the wrapped element toward the user's cursor on hover using spring physics.

import React, { useRef } from 'react';
import { motion, useMotionValue, useSpring } from 'motion/react';
import { springs } from '../../lib/motion-tokens';

interface MagneticProps {
  children: React.ReactNode;
  strength?: number; // 0 to 1 scale of magnetic pull distance
  className?: string;
}

export const Magnetic: React.FC<MagneticProps> = ({
  children,
  strength = 0.35,
  className = '',
}) => {
  const ref = useRef<HTMLDivElement>(null);

  const x = useMotionValue(0);
  const y = useMotionValue(0);

  const springX = useSpring(x, springs.snappy);
  const springY = useSpring(y, springs.snappy);

  const handleMouseMove = (e: React.MouseEvent<HTMLDivElement>) => {
    if (!ref.current) return;
    const { left, top, width, height } = ref.current.getBoundingClientRect();
    const centerX = left + width / 2;
    const centerY = top + height / 2;
    const distanceX = (e.clientX - centerX) * strength;
    const distanceY = (e.clientY - centerY) * strength;
    x.set(distanceX);
    y.set(distanceY);
  };

  const handleMouseLeave = () => {
    x.set(0);
    y.set(0);
  };

  return (
    <motion.div
      ref={ref}
      style={{ x: springX, y: springY }}
      onMouseMove={handleMouseMove}
      onMouseLeave={handleMouseLeave}
      className={`inline-block ${className}`}
    >
      {children}
    </motion.div>
  );
};
