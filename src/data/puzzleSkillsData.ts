import type { JigsawEdgeType, JigsawEdges, PuzzleSkillPiece } from '../types/skills';

export const PUZZLE_ROWS = 4;
export const PUZZLE_COLS = 4;
export const PUZZLE_PIECE_SIZE = 160; // 160x160 base grid units (640x640 total base square)

// Mathematical horizontal seams between col c and c+1
export const PUZZLE_H_SEAMS: JigsawEdgeType[][] = [
  ['tab', 'hole', 'tab'],
  ['hole', 'tab', 'hole'],
  ['tab', 'hole', 'tab'],
  ['hole', 'tab', 'hole'],
];

// Mathematical vertical seams between row r and r+1
export const PUZZLE_V_SEAMS: JigsawEdgeType[][] = [
  ['hole', 'tab', 'hole', 'tab'],
  ['tab', 'hole', 'tab', 'hole'],
  ['hole', 'tab', 'hole', 'tab'],
];

/**
 * Returns edge configuration for piece at (r, c)
 */
export function getPieceEdges(r: number, c: number): JigsawEdges {
  return {
    top: r === 0 ? 'flat' : PUZZLE_V_SEAMS[r - 1][c] === 'tab' ? 'hole' : 'tab',
    right: c === PUZZLE_COLS - 1 ? 'flat' : PUZZLE_H_SEAMS[r][c],
    bottom: r === PUZZLE_ROWS - 1 ? 'flat' : PUZZLE_V_SEAMS[r][c],
    left: c === 0 ? 'flat' : PUZZLE_H_SEAMS[r][c - 1] === 'tab' ? 'hole' : 'tab',
  };
}

